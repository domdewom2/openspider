/// Erzeugt für jeden Typ der Liste [`TYPE_NAMES`] samt Abhängigkeiten eine Datei `<Typ>.ts` unter `dir`.
pub fn export_all(dir: &Path) -> Result<(), ts_rs::ExportError> {
    let cfg = ts_rs::Config::new()
        .with_large_int("number")
        .with_out_dir(dir);
    export_all_with(&cfg)
}

