/// Erste Zeile jeder von ts-rs erzeugten Datei; daran erkennt [`write_gen`] veraltete Ausgaben.
pub const GENERATED_HEADER: &str = "// This file was generated by [ts-rs]";

/// Schreibt die TypeScript-Typen nach `dir`: entfernt zuerst alle früher erzeugten Dateien (erkannt am Kopf
/// [`GENERATED_HEADER`]), damit gelöschte oder umbenannte Typen nicht liegen bleiben, und ruft dann [`export_all`].
pub fn write_gen(dir: &Path) -> std::io::Result<()> {
    remove_generated(dir)?;
    export_all(dir).map_err(|e| std::io::Error::other(e.to_string()))?;
    // Keep the revised UI-state contract free of ts-rs multiline trailing spaces.
    // Scope formatting to this DTO to avoid rewriting unrelated generated contracts.
    let path = dir.join("UiStateJson.ts");
    let generated = std::fs::read_to_string(&path)?;
    let normalized = generated
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n");
    std::fs::write(path, format!("{normalized}\n"))
}

fn remove_generated(dir: &Path) -> std::io::Result<()> {
    let entries = match std::fs::read_dir(dir) {
        Ok(e) => e,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(e) => return Err(e),
    };
    for entry in entries {
        let path = entry?.path();
        if path.is_dir() {
            remove_generated(&path)?;
            // leeres Unterverzeichnis (z. B. serde_json/) entfernen
            if std::fs::read_dir(&path)?.next().is_none() {
                std::fs::remove_dir(&path)?;
            }
        } else if path.extension().is_some_and(|e| e == "ts")
            && std::fs::read_to_string(&path).is_ok_and(|t| t.starts_with(GENERATED_HEADER))
        {
            std::fs::remove_file(&path)?;
        }
    }
    Ok(())
}

